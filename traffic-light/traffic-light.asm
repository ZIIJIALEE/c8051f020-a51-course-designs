public  Init_Device

INIT SEGMENT CODE
    rseg INIT

; Peripheral specific initialization functions,
; Called from the Init_Device label
Reset_Sources_Init:
    mov  WDTCN,     #0DEh
    mov  WDTCN,     #0ADh
    ret

Timer_Init:
    mov  TCON,      #001h
    mov  TMOD,      #011h
    mov  TL0,       #0C0h
    mov  TH0,       #0E0h
	mov  TL1,       #078h
    mov  TH1,       #0ECh
    ret

Interrupts_Init:
    mov  IE,        #08Bh
	mov  IP,		#008h
    ret

; Initialization function for device,
; Call Init_Device from your main program
Init_Device:
    lcall Reset_Sources_Init
    lcall Timer_Init
    lcall Interrupts_Init
    ret

